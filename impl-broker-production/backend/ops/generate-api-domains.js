#!/usr/bin/env node
/**
 * Generate one CloudFormation deployment command per portal.
 *
 * Required environment:
 *   HTTP_API_ID, INTEGRATION_ID, ACM_CERTIFICATE_ARN
 * Optional:
 *   API_STAGE_NAME (default $default), HOSTED_ZONE_ID, PORTALS_FILE
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadPortals } from './portals.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const portalsFile = process.env.PORTALS_FILE || join(here, 'portals.json');
const outDir = join(here, 'generated', 'api-domains');

function required(name) {
  const value = process.env[name];
  if (!value) throw new Error(`missing required env ${name}`);
  return value;
}

const httpApiId = required('HTTP_API_ID');
const integrationId = required('INTEGRATION_ID');
const certificateArn = required('ACM_CERTIFICATE_ARN');
const apiStageName = process.env.API_STAGE_NAME || '$default';
const hostedZoneId = process.env.HOSTED_ZONE_ID || '';

const portals = await loadPortals(portalsFile);
await mkdir(outDir, { recursive: true });

const lines = [
  '#!/usr/bin/env bash',
  'set -euo pipefail',
  '',
  '# Generated by ops/generate-api-domains.js. Review before running.',
  '',
];

for (const portal of portals) {
  const stackName = `${portal.realm}-api-domain`;
  lines.push(
    `aws cloudformation deploy \\`,
    `  --stack-name ${stackName} \\`,
    `  --template-file backend/ops/api-domain.template.yaml \\`,
    `  --capabilities CAPABILITY_IAM \\`,
    `  --parameter-overrides \\`,
    `    HttpApiId=${httpApiId} \\`,
    `    IntegrationId=${integrationId} \\`,
    `    ApiStageName='${apiStageName}' \\`,
    `    PortalHost=${portal.host} \\`,
    `    CertificateArn=${certificateArn} \\`,
    `    BasePath=/api \\`,
    `    HostedZoneId='${hostedZoneId}'`,
    '',
  );
}

const scriptPath = join(outDir, 'deploy.sh');
await writeFile(scriptPath, lines.join('\n'), { mode: 0o700 });

const redirectUris = portals
  .map((p) => `https://kc.gateway-vw.de:8443/realms/${p.realm}/broker/verimi/endpoint`)
  .join('\n');
await writeFile(join(outDir, 'verimi-redirect-uris.txt'), `${redirectUris}\n`);

console.log(`Wrote ${scriptPath} for ${portals.length} portals.`);
